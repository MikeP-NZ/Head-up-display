# PlatformIO pre-build step: gzip web/index.html into src/generated/web_index.h
# so the portal ships inside the firmware image (no filesystem upload needed).
# The home-screen files (app manifest and icons, see tools/make_icons.py) go
# in the same header as WEB_ASSETS, served as they are.
#
# Also stamps the page with a fingerprint of its contents (in place of the
# __PORTAL_BUILD__ placeholder) and puts the same fingerprint in the header as
# WEB_PORTAL_BUILD. The firmware reports it in /api/status, so an open portal
# notices when the display is serving a different page and reloads.
import gzip
import hashlib
import os

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

project = env["PROJECT_DIR"]  # noqa: F821
web = os.path.join(project, "web")
source = os.path.join(web, "index.html")
target = os.path.join(project, "src", "generated", "web_index.h")

# Served at /<name>.
ASSETS = [
    ("manifest.webmanifest", "application/manifest+json"),
    ("icon-180.png", "image/png"),
    ("icon-192.png", "image/png"),
    ("icon-512.png", "image/png"),
]


def c_bytes(data):
    rows = (data[i : i + 20] for i in range(0, len(data), 20))
    return "\n".join("  " + ", ".join(f"0x{b:02x}" for b in row) + "," for row in rows)


with open(source, "rb") as f:
    html = f.read()
build = hashlib.sha256(html).hexdigest()[:10]
payload = gzip.compress(html.replace(b"__PORTAL_BUILD__", build.encode()), compresslevel=9, mtime=0)

parts = [
    "// Generated by scripts/embed_web.py from web/ - do not edit.\n"
    "#pragma once\n"
    "#include <stddef.h>\n"
    "#include <stdint.h>\n\n"
    f'#define WEB_PORTAL_BUILD "{build}"\n'
    f"static const size_t WEB_INDEX_GZ_LEN = {len(payload)};\n"
    "static const uint8_t WEB_INDEX_GZ[] = {\n" + c_bytes(payload) + "\n};\n"
]
entries = []
for i, (name, mime) in enumerate(ASSETS):
    with open(os.path.join(web, name), "rb") as f:
        data = f.read()
    parts.append(f"\nstatic const uint8_t WEB_ASSET_{i}[] = {{\n{c_bytes(data)}\n}};\n")
    entries.append(f'    {{"/{name}", "{mime}", WEB_ASSET_{i}, {len(data)}}},')
parts.append(
    "\nstruct WebAsset {\n  const char* path;\n  const char* type;\n  const uint8_t* data;\n  size_t len;\n};\n"
    "static const WebAsset WEB_ASSETS[] = {\n" + "\n".join(entries) + "\n};\n"
)
header = "".join(parts)

os.makedirs(os.path.dirname(target), exist_ok=True)
existing = open(target).read() if os.path.exists(target) else None
if existing != header:
    with open(target, "w") as f:
        f.write(header)
    print(f"embed_web: {os.path.relpath(source, project)} -> {len(payload)} bytes gzipped, build {build}, "
          f"{len(ASSETS)} home-screen files")
